"""Pure prompt and parsing helpers for Qwen candidate self-computation.

All task-dependent intermediates passed between stages are generated by Qwen. The
evaluator may compute parallel audit values, but this module never inserts those
audit values into a later model prompt.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from typing import Literal

Answer = Literal["YES", "NO"]
Label = Literal["A", "B", "C"]

YES_NO_PATTERN = re.compile(r"\b(YES|NO)\b", re.IGNORECASE)
COUNT_PATTERN = re.compile(r"\bCOUNT\s*:\s*(\d+)\b", re.IGNORECASE)
FINAL_LABEL_PATTERN = re.compile(r"\bFINAL\s*:\s*([ABC])\b", re.IGNORECASE)
CANDIDATE_FINAL_PATTERN = re.compile(
    r"\bFINAL\s*:\s*(ALPHA|BETA|TIE)\b", re.IGNORECASE
)


def format_set(values: Sequence[int]) -> str:
    return "{" + ", ".join(str(value) for value in values) + "}"


def atomic_membership_prompt(candidate: int, subset: Sequence[int]) -> str:
    return (
        "Inspect the literal set in this single membership question. "
        f"Is the integer {candidate} an element of {format_set(subset)}? "
        "Reply with exactly YES or NO."
    )


def parse_yes_no(text: str) -> Answer | None:
    matches = YES_NO_PATTERN.findall(text)
    if not matches:
        return None
    return matches[-1].upper()  # type: ignore[return-value]


def truth_report_pairs(
    qwen_truths: Sequence[Answer | None], reports: Sequence[Answer]
) -> list[tuple[int, Answer | None, Answer]]:
    if len(qwen_truths) != len(reports):
        raise ValueError("Qwen truths and reports must have equal length.")
    return [
        (index, truth, report)
        for index, (truth, report) in enumerate(zip(qwen_truths, reports), start=1)
    ]


def _pair_text(pair: tuple[int, Answer | None, Answer]) -> str:
    question, truth, report = pair
    truth_text = truth if truth is not None else "MISSING"
    return f"Q{question} [truth={truth_text}, report={report}]"


def visible_count_prompt(
    pairs: Sequence[tuple[int, Answer | None, Answer]], *, reverse: bool
) -> str:
    displayed = list(reversed(pairs)) if reverse else list(pairs)
    pair_block = "; ".join(_pair_text(pair) for pair in displayed)
    labels = "; ".join(f"Q{pair[0]}: SAME/DIFFERENT" for pair in displayed)
    return (
        "Compare the two words inside each bracket. For each Q write SAME if truth and "
        "report are identical, otherwise DIFFERENT. Then count the SAME labels. "
        f"{pair_block}. Use exactly: {labels}; COUNT: 0/1/2/3."
    )


def parse_count(text: str, *, maximum: int = 3) -> int | None:
    matches = COUNT_PATTERN.findall(text)
    if not matches:
        return None
    value = int(matches[-1])
    return value if 0 <= value <= maximum else None


def count_adjudication_prompt(
    *,
    forward_draft: str,
    reverse_draft: str,
    pairs: Sequence[tuple[int, Answer | None, Answer]],
) -> str:
    pair_block = "; ".join(_pair_text(pair) for pair in pairs)
    return (
        "Two previous Qwen counting drafts disagree or failed to parse. "
        f"FORWARD DRAFT: {forward_draft} REVERSE DRAFT: {reverse_draft} "
        f"Audit them against these unverified truth/report pairs: {pair_block}. "
        "Independently label Q1,Q2,Q3 SAME or DIFFERENT and count SAME. "
        "End with COUNT: 0, 1, 2, or 3."
    )


def interior_final_prompt(*, first_count: int | None, second_count: int | None, r: float) -> str:
    return (
        "Your own previous model calls produced unverified match counts: "
        f"FIRST candidate ALPHA has {first_count} matches of 3; "
        f"SECOND candidate BETA has {second_count} matches of 3. "
        f"The report reliability is r={r:g}. "
        "If 0<r<0.5, fewer matches means larger weight; if 0.5<r<1, more matches "
        "means larger weight; if r=0.5, weights tie. "
        "A means FIRST larger, B means SECOND larger, C means equal. "
        "End with FINAL: A, B, or C."
    )


def endpoint_positive_prompt(*, qwen_count: int | None, special_count: int) -> str:
    return (
        f"Is the integer {qwen_count} exactly equal to {special_count}? "
        "Reply exactly YES or NO."
    )


def endpoint_count_final_prompt(
    *, first_count: int | None, second_count: int | None, special_count: int
) -> str:
    return (
        "Your own previous model calls produced unverified match counts: "
        f"FIRST candidate ALPHA has {first_count} matches of 3; "
        f"SECOND candidate BETA has {second_count} matches of 3. "
        f"At this endpoint, a candidate has positive likelihood exactly when its count is "
        f"{special_count}. If only FIRST has positive likelihood, answer A. If only SECOND "
        "has positive likelihood, answer B. If both are positive or both are negative, "
        "answer C. End with FINAL: A, B, or C."
    )


def endpoint_final_prompt(*, first_check: Answer | None, second_check: Answer | None) -> str:
    return (
        "Your own previous model calls checked whether each candidate has positive likelihood. "
        f"FIRST candidate ALPHA check={first_check}; SECOND candidate BETA check={second_check}. "
        "If only FIRST is YES, answer A. If only SECOND is YES, answer B. "
        "If both checks are the same, answer C. End with FINAL: A, B, or C."
    )


def interior_candidate_final_prompt(
    *, first_count: int | None, second_count: int | None, r: float
) -> str:
    return (
        "Your own previous model calls produced unverified match counts: "
        f"candidate ALPHA has {first_count} matches of 3; "
        f"candidate BETA has {second_count} matches of 3. "
        f"The report reliability is r={r:g}. "
        "For 0<r<0.5 choose the candidate with fewer matches; for 0.5<r<1 choose "
        "the candidate with more matches; at r=0.5 they tie. "
        "Reply with exactly one line: FINAL: ALPHA, FINAL: BETA, or FINAL: TIE."
    )


def endpoint_candidate_final_prompt(
    *, first_check: Answer | None, second_check: Answer | None
) -> str:
    return (
        "Your own previous model calls checked positive likelihood at the endpoint: "
        f"candidate ALPHA returned {first_check}; candidate BETA returned {second_check}. "
        "If exactly one candidate returned YES, choose that candidate. If both returned the "
        "same answer, they tie. Reply with exactly one line: FINAL: ALPHA, FINAL: BETA, "
        "or FINAL: TIE."
    )


def parse_final_label(text: str) -> Label | None:
    matches = FINAL_LABEL_PATTERN.findall(text)
    if not matches:
        return None
    return matches[-1].upper()  # type: ignore[return-value]


def semantic_from_label(label: Label | None) -> Literal["left", "right", "tie"] | None:
    return {"A": "left", "B": "right", "C": "tie"}.get(label)


def parse_candidate_final(
    text: str,
) -> Literal["left", "right", "tie"] | None:
    matches = CANDIDATE_FINAL_PATTERN.findall(text)
    if not matches:
        return None
    return {"ALPHA": "left", "BETA": "right", "TIE": "tie"}[matches[-1].upper()]


def choose_qwen_count(
    *, forward: int | None, reverse: int | None, adjudicated: int | None
) -> int | None:
    if forward is not None and forward == reverse:
        return forward
    return adjudicated


def membership_audit(
    *, candidate: int, subsets: Sequence[Sequence[int]], qwen_truths: Sequence[Answer | None]
) -> Mapping[str, int]:
    actual = ["YES" if candidate in subset else "NO" for subset in subsets]
    return {
        "correct": sum(predicted == target for predicted, target in zip(qwen_truths, actual)),
        "total": len(actual),
    }
